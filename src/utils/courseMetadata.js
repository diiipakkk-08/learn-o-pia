export function getCourseMetadata(course) {
  if (!course) return null;
  const cId = typeof course === 'string' ? course : (course.id || '');
  const plId = typeof course === 'object' ? (course.playlistId || course.youtubePlaylistId || course.youtube_playlist_id || '') : '';
  const title = typeof course === 'object' ? (course.title || '') : '';
  const titleKey = title.toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 30);

  return (
    COURSE_METADATA_BY_ID[cId] ||
    (plId && COURSE_METADATA_BY_PLAYLIST[plId]) ||
    (titleKey && COURSE_METADATA_BY_TITLE[titleKey]) ||
    null
  );
}

export function resolveCourseBanner(course) {
  if (!course) return 'https://images.unsplash.com/photo-1456513080510-7bf3a84b82f8?auto=format&fit=crop&w=900&q=80';
  const meta = getCourseMetadata(course);
  if (meta && meta.bannerUrl) return meta.bannerUrl;

  // If first video thumbnail available
  if (course.videos && course.videos[0]) {
    const v = course.videos[0];
    const yId = v.youtubeId || (v.url ? (v.url.match(/[?&]v=([^#&]+)/) || [])[1] : null);
    if (yId && !yId.startsWith('PL')) {
      return `https://i.ytimg.com/vi/${yId}/hqdefault.jpg`;
    }
  }

  if (course.bannerUrl && !course.bannerUrl.includes('placeholder')) return course.bannerUrl;
  if (course.banner_url && !course.banner_url.includes('placeholder')) return course.banner_url;

  return 'https://images.unsplash.com/photo-1456513080510-7bf3a84b82f8?auto=format&fit=crop&w=900&q=80';
}

export function resolveCourseLectureCount(course) {
  if (!course) return 24;
  const meta = getCourseMetadata(course);
  if (meta && meta.lectureCount) return meta.lectureCount;

  if (Array.isArray(course.videos) && course.videos.length > 0) {
    return course.videos.length;
  }

  const desc = course.description || course.title || '';
  const match = String(desc).match(/(\d+)\s*lectures?/i);
  if (match) return parseInt(match[1], 10);

  // Deterministic count based on title hash so each course has a unique lecture count (18-46)
  const seed = (course.title || course.id || 'course');
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = ((hash << 5) - hash) + seed.charCodeAt(i);
    hash |= 0;
  }
  return 18 + (Math.abs(hash) % 29);
}
